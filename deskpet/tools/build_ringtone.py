"""Convert an alarm ringtone (mp3, wav, ...) into 16 kHz mono PCM for the speaker.

Writes src/core/audio/ringtone_data.h. Both ends get a short fade so that looping
the clip does not click at the seam.
"""
from __future__ import annotations

import argparse
import array
import json
import wave
from pathlib import Path

import av

ROOT = Path(__file__).resolve().parents[1]
SAMPLE_RATE = 16000  # must match the codec clock in src/core/audio/audio.cpp
FADE_MS = 8
SAMPLES_PER_LINE = 16


def decode(path: Path) -> array.array:
    container = av.open(str(path))
    try:
        stream = next(s for s in container.streams if s.type == "audio")
        resampler = av.AudioResampler(format="s16", layout="mono", rate=SAMPLE_RATE)
        pcm = array.array("h")

        def take(frames) -> None:
            for frame in frames:
                pcm.frombytes(bytes(frame.planes[0])[: frame.samples * 2])

        for frame in container.decode(stream):
            take(resampler.resample(frame))
        take(resampler.resample(None) or [])
        return pcm
    finally:
        container.close()


def fade_ends(pcm: array.array) -> array.array:
    count = min(len(pcm) // 2, SAMPLE_RATE * FADE_MS // 1000)
    for i in range(count):
        gain = i / count
        pcm[i] = int(pcm[i] * gain)
        pcm[len(pcm) - 1 - i] = int(pcm[len(pcm) - 1 - i] * gain)
    return pcm


def render_header(pcm: array.array, source_name: str) -> str:
    lines = []
    for start in range(0, len(pcm), SAMPLES_PER_LINE):
        lines.append("    " + ", ".join(str(v) for v in pcm[start:start + SAMPLES_PER_LINE]) + ",")
    return (
        "#pragma once\n"
        "#include <stdint.h>\n\n"
        f"// Generated by tools/build_ringtone.py from {source_name}.\n"
        f"// {len(pcm)} samples of 16 kHz mono PCM ({len(pcm) / SAMPLE_RATE:.3f} s).\n"
        f"inline constexpr uint32_t RINGTONE_SAMPLES = {len(pcm)};\n"
        "inline constexpr int16_t RINGTONE_PCM[] = {\n"
        + "\n".join(lines)
        + "\n};\n"
    )


def write_wav(path: Path, pcm: array.array) -> None:
    with wave.open(str(path), "wb") as out:
        out.setnchannels(1)
        out.setsampwidth(2)
        out.setframerate(SAMPLE_RATE)
        out.writeframes(pcm.tobytes())


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("input", type=Path, help="ringtone file to convert")
    parser.add_argument("--output", type=Path, default=ROOT / "src/core/audio/ringtone_data.h")
    parser.add_argument("--preview", type=Path, help="also write the converted clip as a WAV file")
    args = parser.parse_args()

    pcm = fade_ends(decode(args.input))
    args.output.write_bytes(render_header(pcm, args.input.name).encode("utf-8"))
    if args.preview:
        write_wav(args.preview, pcm)
    peak = max((abs(v) for v in pcm), default=0)
    print(json.dumps({"samples": len(pcm), "seconds": round(len(pcm) / SAMPLE_RATE, 3), "peak": peak,
                      "output": args.output.as_posix()}))


if __name__ == "__main__":
    main()
